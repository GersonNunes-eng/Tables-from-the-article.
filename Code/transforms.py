import os
import random
import copy
import numpy as np
import torch
import torch.nn as nn
from torch.utils.data import DataLoader, Dataset
import time
from datetime import timedelta
torch.set_num_threads(1)

start_total = time.perf_counter()

SEMENTE_FIXA = 1
os.environ["PYTHONHASHSEED"] = str(SEMENTE_FIXA)

def definir_semente(semente):

    random.seed(semente)
    np.random.seed(semente)
    torch.manual_seed(semente)

    torch.use_deterministic_algorithms(True)

# =====================================================================
# CONFIGURAÇÕES DO EXPERIMENTO
# =====================================================================

N_TESTE = 7
JANELAS = [1,2,3]

MAX_EPOCHS = 100000
PATIENCE = 30000

BATCH_SIZE = 4
LEARNING_RATE = 1e-3

D_MODEL = 16
NHEAD = 2
NUM_LAYERS = 2
DROPOUT = 0.1

# =====================================================================
# CARREGAMENTO E TRANSFORMAÇÃO DOS DADOS
# =====================================================================

todos_dados_puros = np.loadtxt("Demanda_73.txt", dtype=np.float32)

# Transformação logarítmica
dados_log = np.log(todos_dados_puros)

# Min-Max calculado APENAS sobre o conjunto de treinamento
min_val = np.min(dados_log[:66])
max_val = np.max(dados_log[:66])

# Normalização
dados_transformados = (dados_log - min_val) / (max_val - min_val)

# Divisão dos dados
dados_treino_total = dados_transformados[:66]
reais_teste = dados_transformados[66:]

# =====================================================================
# JANELAS
# =====================================================================

def criar_janelas(serie, lookback, forecast):

    X = []
    y = []

    for i in range(
        len(serie) - lookback - forecast + 1
    ):

        X.append(
            serie[i:i + lookback]
        )

        y.append(
            serie[
                i + lookback:
                i + lookback + forecast
            ]
        )

    return np.array(X), np.array(y)


# =====================================================================
# DATASET
# =====================================================================

class DatasetEnergia(Dataset):

    def __init__(self, X, y): # [amostras, janela, 1 variável]

        self.X = torch.tensor(X, dtype=torch.float32).unsqueeze(-1)

        self.y = torch.tensor(y, dtype=torch.float32)

    def __len__(self):

        return len(self.X)

    def __getitem__(self, idx):

        return self.X[idx], self.y[idx] # [amostras, 7 valores futuros]


# =====================================================================
# ARQUITETURA DO TRANSFORMER
# =====================================================================

class TransformerRegressao(nn.Module):

    def __init__(
        self,
        seq_in,
        seq_out,
        d_model=D_MODEL,
        nhead=NHEAD,
        num_layers=NUM_LAYERS,
        dropout=DROPOUT):

        super(TransformerRegressao, self).__init__()

        self.encoder_input = nn.Linear(1, d_model)

        encoder_layer = nn.TransformerEncoderLayer(
            d_model=d_model,
            nhead=nhead,
            batch_first=True,
            dropout=dropout)

        self.transformer_encoder = nn.TransformerEncoder(
            encoder_layer,
            num_layers=num_layers)

        self.decoder_output = nn.Sequential(

            nn.Flatten(),

            nn.Linear(d_model * seq_in, seq_out)
        )


    def forward(self, src):

        src = self.encoder_input(src)

        out = self.transformer_encoder(src)

        out = self.decoder_output(out)

        return out


# =====================================================================
# ARMAZENAMENTO DOS RESULTADOS
# =====================================================================

resultados = []


# =====================================================================
# TREINAMENTO E AVALIAÇÃO
# =====================================================================

for janela in JANELAS:


    # ================================================================
    # INÍCIO DO TEMPO INDIVIDUAL DO MODELO
    # ================================================================

    start_modelo = time.perf_counter()


    print("\n")
    print("=" * 75)

    print(
        f"EXECUTANDO TRANSFORMER "
        f"COM JANELA = {janela}"
    )

    print("=" * 75)


    # ================================================================
    # REINICIALIZAÇÃO DA SEMENTE
    # ================================================================

    definir_semente(SEMENTE_FIXA)


    # ================================================================
    # CRIAÇÃO DAS JANELAS DE TREINAMENTO
    # ================================================================

    X_treino, y_treino = criar_janelas(
        dados_treino_total,
        janela,
        N_TESTE
    )


    dataset_treino = DatasetEnergia(
        X_treino,
        y_treino
    )

    gerador = torch.Generator()

    gerador.manual_seed(
        SEMENTE_FIXA
    )

    dataloader_treino = DataLoader(
        dataset_treino,
        batch_size=BATCH_SIZE,
        shuffle=True,
        generator=gerador
    )

    # ================================================================
    # INICIALIZAÇÃO DO MODELO
    # ================================================================

    definir_semente(SEMENTE_FIXA)

    modelo = TransformerRegressao(
        seq_in=janela,
        seq_out=N_TESTE
    )

    # ================================================================
    # OTIMIZADOR E FUNÇÃO DE PERDA
    # ================================================================

    otimizador = torch.optim.Adam(
        modelo.parameters(),
        lr=LEARNING_RATE
    )

    funcao_perda = nn.MSELoss()

    # ================================================================
    # VARIÁVEIS DO EARLY STOPPING
    # ================================================================

    melhor_perda = float("inf")

    contador_paciencia = 0

    melhores_pesos = None

    epocas_rodadas = 0

    # ================================================================
    # TREINAMENTO
    # ================================================================

    for epoch in range(
        1,
        MAX_EPOCHS + 1
    ):

        modelo.train()

        perda_epoca = 0.0

        for batch_X, batch_y in dataloader_treino:

            otimizador.zero_grad()


            previsoes = modelo(
                batch_X
            )


            perda = funcao_perda(
                previsoes,
                batch_y
            )


            perda.backward()


            otimizador.step()


            perda_epoca += perda.item()

        perda_media = (
            perda_epoca /
            len(dataloader_treino)
        )


        epocas_rodadas = epoch


        # ------------------------------------------------------------
        # Early Stopping
        # ------------------------------------------------------------

        if perda_media < melhor_perda:

            melhor_perda = perda_media

            contador_paciencia = 0
            melhores_pesos = copy.deepcopy(
                modelo.state_dict()
            )


        else:

            contador_paciencia += 1

        if (
            epoch % 50 == 0
            or epoch == 1
        ):

            print(
                f"Época {epoch:06d}/{MAX_EPOCHS} | "
                f"Loss de Treino: {perda_media:.7f}"
            )


        # ------------------------------------------------------------
        # Critério de parada
        # ------------------------------------------------------------

        if contador_paciencia >= PATIENCE:

            print(
                f"\nEarly Stopping acionado "
                f"na época {epoch}."
            )

            break


    # ================================================================
    # RESTAURAÇÃO DOS MELHORES PESOS
    # ================================================================

    if melhores_pesos is not None:

        modelo.load_state_dict(
            melhores_pesos
        )


    # ================================================================
    # PREVISÃO
    # ================================================================

    modelo.eval()

    ultimo_historico_conhecido = (
        dados_treino_total[-janela:]
    )

    entrada_previsao = torch.tensor(
        ultimo_historico_conhecido,
        dtype=torch.float32
    ).unsqueeze(0).unsqueeze(-1)


    with torch.no_grad():

        previsao_normalizada = (
            modelo(
                entrada_previsao
            )
            .squeeze()
            .numpy()
        )


    # ================================================================
    # VALORES REAIS
    # ================================================================

    reais_normalizados = np.array(
        reais_teste,
        dtype=np.float32
    )


    # ================================================================
    # RETORNO PARA A ESCALA LOGARÍTMICA
    # ================================================================

    previsao_log = (
        previsao_normalizada
        * (max_val - min_val)
    ) + min_val


    reais_log = (
        reais_normalizados
        * (max_val - min_val)
    ) + min_val


    # ================================================================
    # RETORNO PARA A ESCALA ORIGINAL
    # ================================================================

    previstos = previsao_log

    reais = reais_log

    # ================================================================
    # MÉTRICAS
    # ================================================================

    mae = np.mean(
        np.abs(
            reais - previstos
        )
    )


    mse = np.mean(
        (reais - previstos) ** 2
    )


    rmse = np.sqrt(
        mse
    )


    mape = np.mean(
        np.abs(
            (reais - previstos)
            / reais
        )
    ) * 100


    # ================================================================
    # TEMPO
    # ================================================================

    end_modelo = time.perf_counter()

    tempo_modelo = (
        end_modelo -
        start_modelo
    )

    # ================================================================
    # EXIBIÇÃO DAS PREVISÕES
    # ================================================================

    print("\n")
    print("-" * 75)

    print(
        f"PREVISÕES PARA TRANSFORMER-{janela}"
    )

    print("-" * 75)


    print(
        f"{'Período':<10}"
        f"{'Observado':>15}"
        f"{'Previsto':>15}"
        f"{'Erro':>15}"
    )


    print("-" * 75)


    for i in range(N_TESTE):

        erro = (
            reais[i]
            - previstos[i]
        )


        print(
            f"{i + 1:<10}"
            f"{reais[i]:>15.6f}"
            f"{previstos[i]:>15.6f}"
            f"{erro:>15.6f}"
        )


    # ================================================================
    # RESULTADOS DO MODELO
    # ================================================================

    print("-" * 75)


    print(
        f"Transformer-{janela}"
    )


    print(
        f"Total de épocas: "
        f"{epocas_rodadas}"
    )


    print(
        f"MSE:  {mse:.7f}"
    )


    print(
        f"RMSE: {rmse:.7f}"
    )


    print(
        f"MAE:  {mae:.7f}"
    )


    print(
        f"MAPE: {mape:.7f}%"
    )


    print(
        f"Tempo de execução: "
        f"{tempo_modelo:.4f} segundos"
    )


    print(
        f"Tempo de execução: "
        f"{timedelta(seconds=tempo_modelo)}"
    )


    # ================================================================
    # ARMAZENAMENTO DOS RESULTADOS
    # ================================================================

    resultados.append({

        "Modelo":
        f"Transformer-{janela}",

        "MSE":
        mse,

        "RMSE":
        rmse,

        "MAE":
        mae,

        "MAPE":
        mape,

        "Epocas":
        epocas_rodadas,

        "Tempo_segundos":
        tempo_modelo
    })


# =====================================================================
# RESULTADOS
# =====================================================================

print("\n")
print("=" * 100)

print(
    "RESULTADOS CONSOLIDADOS DOS MODELOS TRANSFORMER"
)

print("=" * 100)


print(
    f"{'Modelo':<18}"
    f"{'MSE':>15}"
    f"{'RMSE':>15}"
    f"{'MAE':>15}"
    f"{'MAPE (%)':>15}"
    f"{'Épocas':>12}"
    f"{'Tempo (s)':>15}"
)


print("-" * 100)


for resultado in resultados:

    print(
        f"{resultado['Modelo']:<18}"
        f"{resultado['MSE']:>15.7f}"
        f"{resultado['RMSE']:>15.7f}"
        f"{resultado['MAE']:>15.7f}"
        f"{resultado['MAPE']:>15.7f}"
        f"{resultado['Epocas']:>12}"
        f"{resultado['Tempo_segundos']:>15.4f}"
    )


# =====================================================================
# TEMPO TOTAL DOS TRÊS MODELOS
# =====================================================================

end_total = time.perf_counter()


tempo_total = (
    end_total -
    start_total
)


print("\n")
print("=" * 100)

print(
    f"Tempo total de execução dos três modelos: "
    f"{tempo_total:.4f} segundos"
)

print(
    f"Tempo total de execução dos três modelos: "
    f"{timedelta(seconds=tempo_total)}"
)

print("=" * 100)