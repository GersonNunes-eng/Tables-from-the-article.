import os
import random
import time
import numpy as np
import pandas as pd
from sklearn.preprocessing import MinMaxScaler
from sklearn.metrics import mean_squared_error, mean_absolute_error
from xgboost import XGBRegressor

# ============================================================
#  CONFIGURAÇÕES
# ============================================================
CAMINHO = "/content/Demanda_73.txt"

N_TESTE = 7
N_EXECUCOES = 300
LAGS = [1, 2, 3]

# ============================================================
# HIPERPARÂMETROS DO XGBOOST
# ============================================================

N_ESTIMATORS = 100
MAX_DEPTH = 3
LEARNING_RATE = 0.05

SUBSAMPLE = 1.0
COLSAMPLE_BYTREE = 1.0

MIN_CHILD_WEIGHT = 1
REG_ALPHA = 0
REG_LAMBDA = 1

# ============================================================
# LEITURA DA SÉRIE
# ============================================================

serie_original = np.loadtxt(CAMINHO)

print("Número total de observações:", len(serie_original))


# ============================================================
#  TRANSFORMAÇÃO LOGARÍTMICA
# ============================================================

serie_log = np.log(serie_original)

# ============================================================
# DIVISÃO TREINAMENTO / TESTE
# ============================================================

treino_log = serie_log[:-N_TESTE]
teste_log = serie_log[-N_TESTE:]

treino_original = serie_original[:-N_TESTE]
teste_original = serie_original[-N_TESTE:]


print("Observações de treinamento:", len(treino_log))
print("Observações de teste:", len(teste_log))


# ============================================================
# NORMALIZAÇÃO
# ============================================================

scaler = MinMaxScaler(feature_range=(0, 1))

treino_norm = scaler.fit_transform(
    treino_log.reshape(-1, 1)
).flatten()

serie_norm = scaler.transform(
    serie_log.reshape(-1, 1)
).flatten()


# ============================================================
# FUNÇÕES AUXILIARES
# ============================================================

def calcular_metricas(y_real, y_previsto):

    mse = mean_squared_error(
        y_real,
        y_previsto
    )

    rmse = np.sqrt(mse)

    mae = mean_absolute_error(
        y_real,
        y_previsto
    )

    mape = np.mean(
        np.abs(
            (y_real - y_previsto) /
            np.where(y_real != 0, y_real, np.finfo(float).eps)
        )
    ) * 100

    return mse, rmse, mae, mape


def criar_supervisionado(serie, p):

    X = []
    y = []

    for t in range(p, len(serie)):

        X.append(
            serie[t-p:t]
        )

        y.append(
            serie[t]
        )

    return np.array(X), np.array(y)


# ============================================================
# ARMAZENAMENTO DOS RESULTADOS
# ============================================================

resultados = []
previsoes = []

# ============================================================
# EXECUÇÕES
# ============================================================

for p in LAGS:

    print("\n" + "=" * 70)
    print(f"XGBOOST COM {p} DEFASAGEM(NS)")
    print("=" * 70)

    X_treino, y_treino = criar_supervisionado(
        treino_norm,
        p
    )

    print(
        "Dimensão X:",
        X_treino.shape,
        "| Dimensão y:",
        y_treino.shape
    )

    for execucao in range(1, N_EXECUCOES + 1):

        semente = execucao

        print(
            f"Execução {execucao:02d}/{N_EXECUCOES}",
            end="\r"
        )

        np.random.seed(semente)
        random.seed(semente)

        modelo = XGBRegressor(

            n_estimators=N_ESTIMATORS,

            max_depth=MAX_DEPTH,

            learning_rate=LEARNING_RATE,

            subsample=SUBSAMPLE,

            colsample_bytree=COLSAMPLE_BYTREE,

            min_child_weight=MIN_CHILD_WEIGHT,

            reg_alpha=REG_ALPHA,

            reg_lambda=REG_LAMBDA,

            objective="reg:squarederror",

            random_state=semente,

            n_jobs=-1
        )


        # ----------------------------------------------------
        # Treinamento
        # ----------------------------------------------------

        inicio = time.perf_counter()

        modelo.fit(
            X_treino,
            y_treino
        )

        fim = time.perf_counter()

        tempo_treinamento = fim - inicio


        # ----------------------------------------------------
        # PREVISÃO RECURSIVA
        # ----------------------------------------------------

        historico = list(treino_norm)

        previsoes_norm = []


        for passo in range(N_TESTE):

            entrada = np.array(
                historico[-p:]
            ).reshape(1, -1)


            previsao = modelo.predict(
                entrada
            )[0]


            previsoes_norm.append(
                previsao
            )

            historico.append(
                previsao
            )


        previsoes_norm = np.array(
            previsoes_norm
        )


        # ----------------------------------------------------
        # ESCALA LOGARÍTMICA
        # ----------------------------------------------------

        previsoes_log = scaler.inverse_transform(
            previsoes_norm.reshape(-1, 1)
        ).flatten()


        # ----------------------------------------------------
        # ESCALA ORIGINAL
        # ----------------------------------------------------

        previsoes_original = np.exp(
            previsoes_log
        )


        # ----------------------------------------------------
        # MÉTRICAS
        # ----------------------------------------------------

        mse_log, rmse_log, mae_log, mape_log = (
            calcular_metricas(
                teste_log,
                previsoes_log
            )
        )

        mse_original, rmse_original, mae_original, mape_original = (
            calcular_metricas(
                teste_original,
                previsoes_original
            )
        )

        resultados.append({

            "Modelo": "XGBoost",

            "p": p,

            "Execucao": execucao,

            "Semente": semente,

            # Escala log
            "MSE_Log": mse_log,
            "RMSE_Log": rmse_log,
            "MAE_Log": mae_log,
            "MAPE_Log": mape_log,

            # Escala original
            "MSE_Original": mse_original,
            "RMSE_Original": rmse_original,
            "MAE_Original": mae_original,
            "MAPE_Original": mape_original,

            # Tempo
            "Tempo_Treinamento_s": tempo_treinamento
        })


        # ----------------------------------------------------
        # ARMAZENAMENTO DAS PREVISÕES
        # ----------------------------------------------------

        for passo in range(N_TESTE):

            previsoes.append({

                "Modelo": "XGBoost",

                "p": p,

                "Execucao": execucao,

                "Semente": semente,

                "Passo": passo + 1,

                "Real_Log": teste_log[passo],

                "Previsto_Log": previsoes_log[passo],

                "Real_Original": teste_original[passo],

                "Previsto_Original": previsoes_original[passo]
            })


print("\n\nProcessamento concluído.")

df_resultados = pd.DataFrame(
    resultados
)

df_previsoes = pd.DataFrame(
    previsoes
)

# ============================================================
# ESTATÍSTICAS DESCRITIVAS
# ============================================================

estatisticas = []

for p in LAGS:

    dados = df_resultados[ df_resultados["p"] == p  ]

    estatisticas.append({

        "Modelo": "XGBoost",

        "p": p,

        # RMSE
        "RMSE_Log_Media":
            dados["RMSE_Log"].mean(),

        "RMSE_Log_Mediana":
            dados["RMSE_Log"].median(),

        "RMSE_Log_DP":
            dados["RMSE_Log"].std(),

        "RMSE_Log_Min":
            dados["RMSE_Log"].min(),

        "RMSE_Log_Max":
            dados["RMSE_Log"].max(),


        "RMSE_Original_Media":
            dados["RMSE_Original"].mean(),

        "RMSE_Original_Mediana":
            dados["RMSE_Original"].median(),

        "RMSE_Original_DP":
            dados["RMSE_Original"].std(),

        "RMSE_Original_Min":
            dados["RMSE_Original"].min(),

        "RMSE_Original_Max":
            dados["RMSE_Original"].max(),


        # MAE
        "MAE_Log_Media":
            dados["MAE_Log"].mean(),

        "MAE_Log_Mediana":
            dados["MAE_Log"].median(),

        "MAE_Log_DP":
            dados["MAE_Log"].std(),

        "MAE_Original_Media":
            dados["MAE_Original"].mean(),

        "MAE_Original_Mediana":
            dados["MAE_Original"].median(),

        "MAE_Original_DP":
            dados["MAE_Original"].std(),


        # MAPE
        "MAPE_Log_Media":
            dados["MAPE_Log"].mean(),

        "MAPE_Log_Mediana":
            dados["MAPE_Log"].median(),

        "MAPE_Log_DP":
            dados["MAPE_Log"].std(),

        "MAPE_Original_Media":
            dados["MAPE_Original"].mean(),

        "MAPE_Original_Mediana":
            dados["MAPE_Original"].median(),

        "MAPE_Original_DP":
            dados["MAPE_Original"].std(),


        # Tempo (Média, Mediana e Soma Total por Lag)
        "Tempo_Medio_s":
            dados["Tempo_Treinamento_s"].mean(),

        "Tempo_Mediano_s":
            dados["Tempo_Treinamento_s"].median(),

        "Tempo_Total_s":
            dados["Tempo_Treinamento_s"].sum()
    })


df_estatisticas = pd.DataFrame(
    estatisticas
)


# ============================================================
# SALVAR CSV
# ============================================================

ARQUIVO_RESULTADOS = (
    "/content/XGBoost_resultados_30_execucoes.csv"
)

ARQUIVO_PREVISOES = (
    "/content/XGBoost_previsoes_30_execucoes.csv"
)

ARQUIVO_ESTATISTICAS = (
    "/content/XGBoost_estatisticas.csv"
)


df_resultados.to_csv(
    ARQUIVO_RESULTADOS,
    index=False
)

df_previsoes.to_csv(
    ARQUIVO_PREVISOES,
    index=False
)

df_estatisticas.to_csv(
    ARQUIVO_ESTATISTICAS,
    index=False
)

# ============================================================
# EXIBIR RESULTADOS
# ============================================================

pd.set_option("display.max_columns", None)

pd.set_option("display.float_format",lambda x: f"{x:.7f}")

print("\n")
print("=" * 70)
print("ESTATÍSTICAS DESCRITIVAS")
print("=" * 70)

print(df_estatisticas)

print("\n")
print("=" * 70)
print("TEMPO TOTAL DE EXECUÇÃO DO EXPERIMENTO")
print("=" * 70)

tempo_total_geral = df_resultados["Tempo_Treinamento_s"].sum()
print(f"Tempo total somado de todos os treinamentos: {tempo_total_geral:.4f} segundos")
print(f"Tempo total em minutos: {tempo_total_geral / 60:.2f} minutos")

print("\n")
print("=" * 70)
print("ARQUIVOS SALVOS")
print("=" * 70)

print(ARQUIVO_RESULTADOS)
