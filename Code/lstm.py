# =============================================================================
# JANELAS
# =============================================================================

def criar_janelas(serie, num_steps):

    X = []
    y = []

    for i in range(
        len(serie) - num_steps
    ):

        X.append(
            serie[i:i + num_steps]
        )

        y.append(
            serie[i + num_steps]
        )

    return (
        np.array(X, dtype=np.float32),
        np.array(y, dtype=np.float32)
    )

# =============================================================================
# CONFIGURAÇÃO DA LSTM
# =============================================================================

num_inputs = 1
num_hiddens = 64
num_outputs = 1

learning_rate = 0.001

num_epochs = 100000
patience = 30000

# =============================================================================
# MODELO LSTM IMPLEMENTAÇÃO DO PYTORCH
# =============================================================================

class ModeloLSTM(nn.Module):

    def __init__(
        self,
        num_inputs,
        num_hiddens,
        num_outputs
    ):

        super().__init__()

        self.lstm = nn.LSTM(
            input_size=num_inputs,
            hidden_size=num_hiddens,
            num_layers=1,
            batch_first=True
        )

        self.fc = nn.Linear(
            num_hiddens,
            num_outputs
        )

    def forward(self, X):

        output, (h_n, c_n) = self.lstm(X)

        ultimo_output = output[:, -1, :]

        y = self.fc(
            ultimo_output
        )

        return y

# =============================================================================
# TREINAMENTO
# =============================================================================

def treinar_lstm(num_steps):

    print("\n")
    print("=" * 80)
    print(
        f"INICIANDO LSTM COM "
        f"{num_steps} INFORMAÇÃO(ÕES) PASSADA(S)"
    )
    print("=" * 80)

    X_np, y_np = criar_janelas(
        serie_treino_norm,
        num_steps
    )

    print(
        "\nNúmero de amostras de treinamento:",
        len(X_np)
    )

    print(
        "Formato das entradas:",
        X_np.shape
    )

    X_train = torch.tensor(
        X_np,
        dtype=torch.float32,
        device=device
    )

    y_train = torch.tensor(
        y_np,
        dtype=torch.float32,
        device=device
    )

    X_train = X_train.unsqueeze(-1)

    # -------------------------------------------------------------------------
    # Modelo
    # -------------------------------------------------------------------------

    model = ModeloLSTM(
        num_inputs=num_inputs,
        num_hiddens=num_hiddens,
        num_outputs=num_outputs
    ).to(device)

    # -------------------------------------------------------------------------
    # Otimizador
    # -------------------------------------------------------------------------

    optimizer = torch.optim.Adam(
        model.parameters(),
        lr=learning_rate
    )

    # -------------------------------------------------------------------------
    # Função de perda
    # -------------------------------------------------------------------------

    loss_fn = nn.MSELoss()

    # -------------------------------------------------------------------------
    # Melhor modelo
    # -------------------------------------------------------------------------

    best_loss = float("inf")

    best_state_dict = None

    contador = 0

    inicio = time.time()

    # -------------------------------------------------------------------------
    # Treinamento
    # -------------------------------------------------------------------------

    for epoch in range(num_epochs):

        model.train()

        pred = model(
            X_train
        ).squeeze(-1)

        loss = loss_fn(
            pred,
            y_train
        )

        optimizer.zero_grad()

        loss.backward()

        optimizer.step()

        valor_loss = loss.item()

        if valor_loss < best_loss:

            best_loss = valor_loss

            best_state_dict = {
                key: value.detach().clone()
                for key, value
                in model.state_dict().items()
            }

            contador = 0

        else:

            contador += 1

        if (epoch + 1) % 5000 == 0:

            print(
                f"Época {epoch + 1:6d} | "
                f"Loss = {valor_loss:.10f}"
            )

        # ---------------------------------------------------------------------
        # Early stopping
        # ---------------------------------------------------------------------

        if contador >= patience:

            print(
                f"\nEarly stopping na época "
                f"{epoch + 1}"
            )

            break

    # -------------------------------------------------------------------------
    # Melhor modelo
    # -------------------------------------------------------------------------

    if best_state_dict is not None:

        model.load_state_dict(
            best_state_dict
        )

    tempo = time.time() - inicio

    print(
        "\nMelhor Loss:",
        best_loss
    )

    print(
        "Épocas executadas:",
        epoch + 1
    )

    print(
        "Tempo de treinamento:",
        tempo,
        "segundos"
    )

    return (
        model,
        best_loss,
        epoch + 1,
        tempo
    )


