def calcular_metricas(reais, previsoes):

    mse = mean_squared_error(reais, previsoes)

    rmse = np.sqrt(mse)

    mae = mean_absolute_error(reais, previsoes)

    mape = np.mean(
        np.abs((reais - previsoes) / reais)
    ) * 100

    return mse, rmse, mae, mape

