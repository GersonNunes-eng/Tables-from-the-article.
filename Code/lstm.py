def prever_um_passo(
    janela,
    model,
    num_steps
):

    model.eval()

    X = torch.tensor(
        janela,
        dtype=torch.float32,
        device=device
    )

    X = X.reshape(
        1,
        num_steps,
        1
    )

    with torch.no_grad():

        previsao = (
            model(X)
            .squeeze()
            .item()
        )

    return previsao

def fazer_previsao(
    model,
    num_steps
):

    historico = list(
        serie_treino_norm
    )

    previsoes_norm = []

    for i in range(n_teste):

        janela = historico[
            -num_steps:
        ]

        previsao = prever_um_passo(
            janela,
            model,
            num_steps
        )

        previsoes_norm.append(
            previsao
        )

        historico.append(
            previsao
        )

    return np.array(
        previsoes_norm
    )

def voltar_escala_original(previsoes_norm):

    # Volta da normalização

    previsoes_log = scaler.inverse_transform(
        previsoes_norm.reshape(-1, 1)
    ).flatten()

    # Volta do logaritmo

    previsoes = np.exp(
        previsoes_log
    )

    return (
        previsoes,
        previsoes_log
    )

